export function GamificationProvider({ children }) {
  const { showToast } = useNotification();

  // Load from localStorage or initialize with sensible demo defaults
  const [xp, setXp] = useState(() => {
    const saved = localStorage.getItem('healthai_user_xp');
    return saved !== null ? parseInt(saved, 10) : 340;
  });

  const [streak, setStreak] = useState(() => {
    const saved = localStorage.getItem('healthai_user_streak');
    return saved !== null ? parseInt(saved, 10) : 5;
  });

  const [quests, setQuests] = useState(() => {
    const saved = localStorage.getItem('healthai_daily_quests');
    if (saved) {
      try { return JSON.parse(saved); } catch {}
    }
    return [
      { id: 'water', label: 'Log 250ml Water Intake', xp: 25, completed: false, icon: '💧', category: 'Nutrition' },
      { id: 'symptom', label: 'Complete Daily Symptom Check', xp: 40, completed: false, icon: '📝', category: 'Surveillance' },
      { id: 'aqi', label: 'Review City AQI & Air Radar', xp: 30, completed: true, icon: '🌤️', category: 'Environment' },
      { id: 'vitals', label: 'Sync Wearable Vitals (HR & SpO2)', xp: 50, completed: true, icon: '💓', category: 'Vitals' },
      { id: 'vault', label: 'Backup Health Record to Vault', xp: 60, completed: false, icon: '🔐', category: 'Security' },
    ];
  });

  const [rewardsModalOpen, setRewardsModalOpen] = useState(false);
  const [levelUpData, setLevelUpData] = useState(null);

  // Sync state to localStorage
  useEffect(() => {
    localStorage.setItem('healthai_user_xp', xp.toString());
  }, [xp]);

  useEffect(() => {
    localStorage.setItem('healthai_user_streak', streak.toString());
  }, [streak]);

  useEffect(() => {
    localStorage.setItem('healthai_daily_quests', JSON.stringify(quests));
  }, [quests]);

  // Compute Current Level and Progress
  let currentTier = LEVEL_TIERS[0];
  let nextTier = LEVEL_TIERS[1];

  for (let i = LEVEL_TIERS.length - 1; i >= 0; i--) {
    if (xp >= LEVEL_TIERS[i].xpRequired) {
      currentTier = LEVEL_TIERS[i];
      nextTier = LEVEL_TIERS[i + 1] || null;
      break;
    }
  }

  const currentLevel = currentTier.level;
  const xpInCurrentLevel = xp - currentTier.xpRequired;
  const xpNeededForNext = nextTier ? nextTier.xpRequired - xp : 0;
  const levelTotalRange = nextTier ? nextTier.xpRequired - currentTier.xpRequired : 100;
  const levelProgressPct = nextTier
    ? Math.min(Math.max((xpInCurrentLevel / levelTotalRange) * 100, 0), 100)
    : 100;

  // Award points
  const awardXP = useCallback((amount, reason = '') => {
    setXp(prevXp => {
      const newXp = prevXp + amount;

      // Check if leveled up
      const oldTier = LEVEL_TIERS.reduce((acc, t) => (prevXp >= t.xpRequired ? t : acc), LEVEL_TIERS[0]);
      const newTier = LEVEL_TIERS.reduce((acc, t) => (newXp >= t.xpRequired ? t : acc), LEVEL_TIERS[0]);

      if (newTier.level > oldTier.level) {
        setLevelUpData(newTier);
        showToast(`🎉 LEVEL UP! You reached Level ${newTier.level}: ${newTier.title}!`, 'success', 5000);
      } else {
        showToast(`+${amount} XP Earned! ${reason ? `(${reason})` : ''}`, 'success', 2500);
      }

      return newXp;
    });
  }, [showToast]);

  // Complete a quest
  const completeQuest = useCallback((questId) => {
    setQuests(prev => {
      const target = prev.find(q => q.id === questId);
      if (!target || target.completed) return prev;

      awardXP(target.xp, target.label);

      return prev.map(q => (q.id === questId ? { ...q, completed: true } : q));
    });
  }, [awardXP]);

  const claimPrize = useCallback((tierLevel) => {
    const tier = LEVEL_TIERS.find(t => t.level === tierLevel);
    if (!tier) return;
    if (xp < tier.xpRequired) {
      showToast(`Locked! ${tier.xpRequired - xp} more XP needed to unlock this prize.`, 'warning');
      return;
    }
    showToast(`🎁 Claimed Prize: ${tier.prize}! Added to your profile.`, 'success', 4000);
  }, [xp, showToast]);

  return (
    <GamificationContext.Provider
      value={{
        xp,
        currentLevel,
        currentTier,
        nextTier,
        xpNeededForNext,
        levelProgressPct,
        streak,
        quests,
        awardXP,
        completeQuest,
        claimPrize,
        rewardsModalOpen,
        setRewardsModalOpen,
        levelUpData,
        setLevelUpData,
        allTiers: LEVEL_TIERS,
      }}
    >
      {children}
    </GamificationContext.Provider>
  );
}

export function useGamification() {
  const context = useContext(GamificationContext);
  if (!context) {
    throw new Error('useGamification must be used within GamificationProvider');
  }
  return context;
}
